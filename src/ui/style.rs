//! Палитра Dark Material UI (alpha 0.9) и мелкие фабрики узлов.

use bevy::prelude::*;

/// Фон панелей.
pub fn background() -> Color {
    Color::srgba(0.13, 0.13, 0.13, 0.90)
}

/// Поверхность кнопки (обычная).
pub fn surface() -> Color {
    Color::srgba(0.20, 0.20, 0.20, 0.90)
}

/// Поверхность кнопки при наведении.
pub fn surface_hover() -> Color {
    Color::srgba(0.30, 0.30, 0.30, 0.90)
}

/// Активная кнопка (например, выбранная скорость).
pub fn surface_active() -> Color {
    Color::srgba(0.35, 0.52, 0.85, 0.90)
}

/// Приглушённая (недоступная в текущем режиме) кнопка инструментов.
pub fn surface_disabled() -> Color {
    Color::srgba(0.16, 0.16, 0.16, 0.60)
}

/// Оверлей модального окна. Деревья технологий/институтов перешли на
/// глухой полноэкранный фон; полупрозрачный оверлей останется для
/// будущих модалок поверх мира.
#[allow(dead_code)]
pub fn overlay() -> Color {
    Color::srgba(0.0, 0.0, 0.0, 0.45)
}

/// Глухой оверлей пауз-меню: мир позади затемнён сильнее, чем у
/// обычных модалок, чтобы строки меню читались поверх карты.
pub fn overlay_strong() -> Color {
    Color::srgba(0.0, 0.0, 0.0, 0.75)
}

/// Кнопка, ожидающая назначения клавиши (захват бинда).
pub fn surface_capture() -> Color {
    Color::srgba(0.42, 0.45, 0.52, 0.90)
}

/// Опасные действия (выход из игры): красный, чтобы не нажать случайно.
pub fn danger() -> Color {
    Color::srgba(0.85, 0.30, 0.28, 0.90)
}

/// Основной цвет текста.
pub fn text() -> Color {
    Color::srgba(0.92, 0.92, 0.92, 0.90)
}

/// Приглушённый текст.
pub fn text_dim() -> Color {
    Color::srgba(0.70, 0.70, 0.70, 0.90)
}

/// Разделительная линия.
pub fn border() -> Color {
    Color::srgba(0.38, 0.38, 0.38, 0.90)
}
