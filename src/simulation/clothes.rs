//! Одежда как общая система существа (задел под холод и погоду,
//! GAME_DESIGN 3.5 — потребность «Температура»).
//!
//! Одежда делится по частям тела, как броня, но защищает не от урона,
//! а от влияния среды: тепло предмета смягчает холод окружения.
//! Модуль — основа: потребителей (расчёт комфортной температуры,
//! урона от холода) пока нет, они появятся вместе с погодой.
//! Предметов одежды тоже пока нет — системы ждут первых видов.

use super::items::{Inventory, ItemKind};

/// Максимум шкалы тепла (индикатор UI), поинтов.
pub const WARMTH_MAX: f32 = 100.0;

/// Тепло предмета, поинтов шкалы. Не-одежда и будущие предметы без
/// утепления дают 0.0 — новые предметы не должны требовать правки здесь.
/// С первыми предметами одежды превращается в match по видам
/// (как `protection_of` в `armor.rs`).
#[allow(unused)] // потребителей тепла пока нет — основа под погоду
pub fn warmth_of(kind: ItemKind) -> f32 {
    let _ = kind;
    0.0
}

/// Суммарное тепло сущности по надетым предметам одежды, поинтов
/// (0.0–`WARMTH_MAX`). Считаются только слоты одежды: предмет в основном
/// слоте или мусорке не считается надетым.
#[allow(unused)] // потребителей тепла пока нет — основа под погоду
pub fn warmth(inventory: &Inventory) -> f32 {
    let mut total = 0.0;
    for stack in inventory.clothes.iter().flatten() {
        total += warmth_of(stack.kind);
    }
    total.clamp(0.0, WARMTH_MAX)
}
